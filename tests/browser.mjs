import { createRequire } from 'node:module';
import { mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
import { previewServer } from '../scripts/preview.mjs';
const { chromium } = createRequire(import.meta.url)('playwright');
const server = previewServer();
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
let browser;
try {
  browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_CHANNEL ? { channel: process.env.BROWSER_CHANNEL } : {}) });
  const page = await browser.newPage({ viewport: { width: 900, height: 1100 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`http://127.0.0.1:${server.address().port}`);
  const card = page.locator('#card');
  await card.locator('.room').first().waitFor();
  assert.equal(await card.locator('.room').count(), 5);
  assert.equal(await card.locator('.start').isDisabled(), true);
  await page.evaluate(() => {
    demo.hass.states[demo.start].state = '2026-10-06T17:27:30.003139+00:00';
    demo.hass.states[demo.ids[0]].state = 'on';
    demo.card.hass = { ...demo.hass };
  });
  assert.equal(await card.locator('.tag').innerText(), 'PROTOTYP · 0.1.1');
  assert.equal(await card.locator('.start').isEnabled(), true, 'HA selection with timestamp button enables start');
  await card.locator('[data-action="reset"]').click();
  assert.equal(await card.locator('.start').isEnabled(), true, 'discarded draft retains HA selection and enabled start');
  await page.evaluate(() => { demo.hass.states[demo.ids[0]].state = 'off'; demo.card.hass = { ...demo.hass }; });
  assert.equal(await card.locator('.start').isDisabled(), true);
  await card.locator('input[data-room]').nth(1).check();
  assert.equal(await card.locator('.start').isEnabled(), true, 'local selection enables start while actual switches are off');
  assert.equal(await page.evaluate(() => demo.hass.states[demo.ids[1]].state), 'off');
  for (const state of ['2026-10-06T17:27:30.003139+00:00', 'unknown', 'unavailable']) {
    await page.evaluate(state => { demo.hass.states[demo.start].state = state; demo.card.hass = { ...demo.hass }; }, state);
    assert.equal(await card.locator('.start').isEnabled(), true, 'start button state does not affect enablement');
  }
  await card.locator('input[data-room]').nth(0).check();
  await card.locator('[data-expand]').nth(0).click();
  await card.locator('[data-expand]').nth(1).click();
  await card.locator('[data-mode]').nth(0).selectOption('Mop');
  assert.equal(await card.locator('[data-mode]').nth(1).inputValue(), 'Mop');
  assert.equal(await page.evaluate(() => demo.calls.length), 0, 'editing must not send commands');
  assert.equal(await card.locator('button').filter({ hasText: /^Save settings$/ }).isDisabled(), true);
  await mkdir(new URL('../artifacts/', import.meta.url), { recursive: true });
  await page.screenshot({ path: fileURLToPath(new URL('../artifacts/desktop.png', import.meta.url)), fullPage: true });
  await page.locator('#theme').click();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: fileURLToPath(new URL('../artifacts/mobile-dark.png', import.meta.url)), fullPage: true });
  await card.locator('.start').click();
  await page.waitForFunction(() => demo.calls.some(c => c.domain === 'button'));
  assert.equal(await page.evaluate(() => demo.calls.filter(c => c.domain === 'button').length), 1);
  assert.equal(await card.locator('.start').isEnabled(), true, 'local selection remains the enablement criterion after a request');
  assert.equal(await page.evaluate(() => demo.hass.states[demo.ids[0]].state), 'on');
  await page.locator('#settings').click();
  const editor = page.locator('dyson-cleaning-planner-card-editor');
  await editor.locator('[data-key="unsupported_settings"]').selectOption('hidden');
  await card.locator('[data-expand]').first().click();
  assert.equal(await card.locator('.field').filter({ hasText: 'Water level' }).count(), 0);
  await editor.locator('[data-include]').first().uncheck();
  assert.equal(await card.locator('.room').count(), 4);
  await page.locator('#offline').click();
  assert.equal(await card.locator('.start').isEnabled(), true, 'live vacuum state does not gate local enablement');
  const callsBefore = await page.evaluate(() => demo.calls.length);
  await card.locator('.start').click();
  assert.equal(await page.evaluate(() => demo.calls.length), callsBefore, 'execution still rejects an offline vacuum');
  await card.locator('input[data-room]').first().uncheck();
  assert.equal(await card.locator('.start').isDisabled(), true, 'no local selection disables start even if a real switch remains on');
  assert.deepEqual(errors, []);
  console.log('Browser checks passed: local-selection-only start enablement, ignored button states, execution checks, discovery, draft, editor and rendering.');
} finally { await browser?.close(); await new Promise(resolve => server.close(resolve)); }
